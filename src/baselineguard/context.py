"""Generate machine-consumable Web feature policy context for AI coding agents.

The generated block is idempotent: re-running the command replaces only the
marked region and preserves everything the human author wrote around it.
"""

from __future__ import annotations

from pathlib import Path
from typing import Dict, List, Tuple

from . import __version__
from .rules import Ruleset
from .verdict import Policy

FORMATS = ("agents-md", "claude-md", "cursorrules", "markdown")
DEFAULT_OUTPUTS = {
    "agents-md": "AGENTS.md",
    "claude-md": "CLAUDE.md",
    "cursorrules": ".cursorrules",
    "markdown": "WEB_BASELINE_POLICY.md",
}

_INSTRUCTIONS = [
    "Before writing or modifying HTML, CSS or JavaScript, consult the ALLOW / REVIEW / DENY lists below.",
    "Never introduce a feature from the DENY list. Replace existing occurrences when you touch that file.",
    "A feature from the REVIEW list is allowed only with an explicit, documented degradation path, and only after the human author approves it.",
    "Do not 'modernise' working code to a newer feature merely because it is newer; prefer the smallest widely supported construct.",
    "When adding a new dependency or snippet, verify it does not silently pull in a feature outside the ALLOW list.",
]


def _buckets(ruleset: Ruleset, policy: Policy) -> Tuple[List, List, List]:
    allow, review, deny = [], [], []
    for rule in ruleset.rules:
        if rule.status == "deprecated":
            deny.append(rule)
        elif rule.status == "limited":
            (review if policy.allow_limited else deny).append(rule)
        elif rule.status == "newly":
            (allow if policy.allow_newly else review).append(rule)
        elif rule.baseline_year is not None and rule.baseline_year <= policy.baseline_year:
            allow.append(rule)
        else:
            review.append(rule)
    key = lambda r: (r.baseline_year or 9999, r.id)
    return sorted(allow, key=key), sorted(review, key=key), sorted(deny, key=key)


def markers(fmt: str) -> Tuple[str, str]:
    if fmt == "cursorrules":
        return "# baselineguard:begin", "# baselineguard:end"
    return "<!-- baselineguard:begin -->", "<!-- baselineguard:end -->"


def build_context(ruleset: Ruleset, policy: Policy, fmt: str = "agents-md") -> str:
    if fmt not in FORMATS:
        raise ValueError(f"unknown context format: {fmt}")
    allow, review, deny = _buckets(ruleset, policy)
    begin, end = markers(fmt)
    is_plain = fmt == "cursorrules"

    def h(text: str) -> str:
        return text if is_plain else f"## {text}"

    def sub(text: str) -> str:
        return text if is_plain else f"### {text}"

    lines: List[str] = [begin]
    if not is_plain:
        lines.append("")
    title = {
        "agents-md": "Web Platform Feature Policy (for AI coding agents)",
        "claude-md": "Web Platform Feature Policy (Claude / coding agents)",
        "cursorrules": "Web Platform Feature Policy - BaselineGuard",
        "markdown": "Web Platform Feature Policy",
    }[fmt]
    lines.append(h(title))
    lines.append("")
    lines.append(
        f"Generated by BaselineGuard {__version__} | ruleset {ruleset.name} {ruleset.version} "
        f"({len(ruleset.rules)} rules) | target baseline {policy.baseline_label} "
        f"(widely <= {policy.baseline_year}) | allow-newly={str(policy.allow_newly).lower()} "
        f"allow-limited={str(policy.allow_limited).lower()}"
    )
    lines.append("This block is machine-generated. Do not edit between the markers; edit the policy flags instead.")
    lines.append("")
    lines.append(sub("Instructions"))
    lines.append("")
    for i, instr in enumerate(_INSTRUCTIONS, 1):
        lines.append(f"{i}. {instr}")
    lines.append("")

    for label, group in (("ALLOW - safe to use", allow),
                         ("REVIEW - requires explicit approval", review),
                         ("DENY - forbidden", deny)):
        lines.append(sub(f"{label} ({len(group)})"))
        lines.append("")
        if not group:
            lines.append("(none)")
            lines.append("")
            continue
        if is_plain:
            for r in group:
                year = r.baseline_year if r.baseline_year is not None else "n/a"
                lines.append(f"- {r.id} [{r.category}/{r.status}, baseline {year}]: {r.suggestion}")
        else:
            lines.append("| Feature | Category | Status | Baseline | Guidance | Reference |")
            lines.append("| --- | --- | --- | --- | --- | --- |")
            for r in group:
                year = r.baseline_year if r.baseline_year is not None else "n/a"
                suggestion = r.suggestion.replace("|", "\\|")
                lines.append(
                    f"| `{r.id}` | {r.category} | {r.status} | {year} | {suggestion} | "
                    f"[MDN]({r.reference}) |"
                )
        lines.append("")

    lines.append(
        f"Regenerate: `baselineguard context --baseline {policy.baseline_label} "
        f"--format {fmt} --out {DEFAULT_OUTPUTS[fmt]}`"
    )
    if not is_plain:
        lines.append("")
    lines.append(end)
    return "\n".join(lines)


def write_context(path: Path, content: str, fmt: str) -> str:
    """Insert or replace the marked block. Returns created|updated|unchanged."""
    begin, end = markers(fmt)
    if path.is_file():
        existing = path.read_text(encoding="utf-8")
        i, j = existing.find(begin), existing.find(end)
        if i != -1 and j != -1 and j > i:
            j += len(end)
            merged = existing[:i] + content + existing[j:]
            if merged == existing:
                return "unchanged"
            path.write_text(merged, encoding="utf-8")
            return "updated"
        merged = existing.rstrip("\n") + "\n\n" + content + "\n"
        path.write_text(merged, encoding="utf-8")
        return "updated"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content + "\n", encoding="utf-8")
    return "created"
